function normalizeLanguage(language) {
  if (!language) return null;
  const value = String(language).trim();
  const lower = value.toLowerCase();
  if (lower === "zh") return "zh-Hans";
  if (lower === "en") return "en";
  if (lower === "ja") return "ja";
  if (lower === "de") return "de";
  if (lower === "zh-hant" || lower === "zh-tw" || lower === "zh-hk" || lower === "zh-mo") return "zh-Hant";
  if (lower === "zh-hans" || lower.startsWith("zh-cn") || lower.startsWith("zh-sg")) return "zh-Hans";
  if (lower.startsWith("en-")) return "en";
  if (lower.startsWith("ja-")) return "ja";
  if (lower.startsWith("de-")) return "de";
  if (lower.startsWith("zh-")) return "zh-Hans";
  return PH_TRANSLATIONS[value] ? value : null;
}

function detectBrowserLanguage() {
  const candidates = [
    ...(navigator.languages || []),
    navigator.language,
    navigator.userLanguage
  ].filter(Boolean);

  for (const candidate of candidates) {
    const normalized = normalizeLanguage(candidate);
    if (normalized) return normalized;
  }
  return "zh-Hans";
}

function queryLanguagePreference() {
  try {
    const params = new URLSearchParams(window.location.search);
    return normalizeLanguage(params.get("lang"));
  } catch (_) {
    return null;
  }
}

function getTranslation(lang, key) {
  const locale = PH_TRANSLATIONS[lang] || PH_TRANSLATIONS.en;
  return locale[key] ?? PH_TRANSLATIONS.en[key] ?? PH_TRANSLATIONS["zh-Hans"][key] ?? "";
}

function updateLanguageSelectWidth(select) {
  const selectedText = select.selectedOptions[0]?.textContent?.trim() || select.value;
  const measurer = updateLanguageSelectWidth.measurer || document.createElement("span");
  const styles = window.getComputedStyle(select);

  if (!updateLanguageSelectWidth.measurer) {
    measurer.setAttribute("aria-hidden", "true");
    Object.assign(measurer.style, {
      position: "absolute",
      visibility: "hidden",
      whiteSpace: "nowrap",
      pointerEvents: "none",
    });
    document.body.appendChild(measurer);
    updateLanguageSelectWidth.measurer = measurer;
  }

  measurer.style.font = styles.font;
  measurer.textContent = selectedText;
  select.style.setProperty("--lang-select-width", `${Math.ceil(measurer.getBoundingClientRect().width) + 4}px`);
}

function closeLanguageMenu(switcher) {
  const button = switcher.querySelector(".lang-button");
  switcher.classList.remove("is-open");
  if (button) button.setAttribute("aria-expanded", "false");
}

function syncLanguageControl(select) {
  updateLanguageSelectWidth(select);

  const switcher = select.closest(".lang-switch");
  if (!switcher) return;

  const selectedText = select.selectedOptions[0]?.textContent?.trim() || select.value;
  const button = switcher.querySelector(".lang-button");
  if (button) {
    button.textContent = selectedText;
    button.setAttribute("aria-label", select.getAttribute("aria-label") || "Website language");
  }

  switcher.querySelectorAll("[data-lang-option]").forEach((optionButton) => {
    optionButton.setAttribute("aria-selected", optionButton.dataset.langValue === select.value ? "true" : "false");
  });
}

function enhanceLanguageSelect(select) {
  const switcher = select.closest(".lang-switch");
  if (!switcher || switcher.classList.contains("is-enhanced")) return;

  const button = document.createElement("button");
  button.type = "button";
  button.className = "lang-button";
  button.setAttribute("aria-haspopup", "listbox");
  button.setAttribute("aria-expanded", "false");
  button.setAttribute("aria-label", select.getAttribute("aria-label") || "Website language");

  const menu = document.createElement("div");
  menu.className = "lang-menu";
  menu.setAttribute("role", "listbox");

  Array.from(select.options).forEach((option) => {
    const optionButton = document.createElement("button");
    optionButton.type = "button";
    optionButton.setAttribute("role", "option");
    optionButton.dataset.langOption = "";
    optionButton.dataset.langValue = option.value;
    if (option.dataset.i18n) optionButton.dataset.i18n = option.dataset.i18n;
    optionButton.textContent = option.textContent;
    optionButton.addEventListener("click", () => {
      applyLanguage(option.value);
      closeLanguageMenu(switcher);
      button.focus();
    });
    optionButton.addEventListener("keydown", (event) => {
      if (event.key === "Escape") {
        event.preventDefault();
        closeLanguageMenu(switcher);
        button.focus();
      }
    });
    menu.appendChild(optionButton);
  });

  button.addEventListener("click", () => {
    const willOpen = !switcher.classList.contains("is-open");
    document.querySelectorAll(".lang-switch.is-open").forEach(closeLanguageMenu);
    switcher.classList.toggle("is-open", willOpen);
    button.setAttribute("aria-expanded", willOpen ? "true" : "false");
  });

  button.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeLanguageMenu(switcher);
      return;
    }
    if (event.key === "ArrowDown" || event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      switcher.classList.add("is-open");
      button.setAttribute("aria-expanded", "true");
      switcher.querySelector('[data-lang-option][aria-selected="true"]')?.focus();
    }
  });

  switcher.insertBefore(button, select);
  switcher.appendChild(menu);
  switcher.classList.add("is-enhanced");
  syncLanguageControl(select);
}

function applyLanguage(language) {
  const lang = normalizeLanguage(language) || "zh-Hans";
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    const value = getTranslation(lang, key);
    if (value) node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-title]").forEach((node) => {
    const key = node.getAttribute("data-i18n-title");
    const value = getTranslation(lang, key);
    if (value) node.setAttribute("title", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const key = node.getAttribute("data-i18n-alt");
    const value = getTranslation(lang, key);
    if (value) node.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria-label");
    const value = getTranslation(lang, key);
    if (value) node.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-content]").forEach((node) => {
    const key = node.getAttribute("data-i18n-content");
    const value = getTranslation(lang, key);
    if (value) node.setAttribute("content", value);
  });

  document.querySelectorAll("[data-lang-src-zh][data-lang-src-en]").forEach((node) => {
    const source = lang === "zh-Hans" || lang === "zh-Hant" ? node.dataset.langSrcZh : node.dataset.langSrcEn;
    if (source && node.getAttribute("src") !== source) node.setAttribute("src", source);
  });

  document.querySelectorAll(".lang-select").forEach((select) => {
    if (select.value !== lang) select.value = lang;
    syncLanguageControl(select);
  });

  const titleKey = document.body.dataset.titleKey;
  const titleValue = titleKey ? getTranslation(lang, titleKey) : "";
  if (titleValue) {
    document.title = titleValue === "PhotoHarbor" ? "PhotoHarbor" : `${titleValue} | PhotoHarbor`;
  }

  localStorage.setItem("ph-lang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const queryLanguage = queryLanguagePreference();
  const savedLanguage = normalizeLanguage(localStorage.getItem("ph-lang"));
  const initial = queryLanguage || savedLanguage || detectBrowserLanguage();
  document.querySelectorAll(".lang-select").forEach(enhanceLanguageSelect);
  applyLanguage(initial);

  document.querySelectorAll(".lang-select").forEach((select) => {
    select.addEventListener("change", (event) => applyLanguage(event.target.value));
  });

  document.addEventListener("click", (event) => {
    document.querySelectorAll(".lang-switch.is-open").forEach((switcher) => {
      if (!switcher.contains(event.target)) closeLanguageMenu(switcher);
    });
  });

  const revealItems = document.querySelectorAll(".reveal");
  revealItems.forEach((item) => {
    const delay = Number(item.dataset.revealDelay || 0);
    item.style.setProperty("--reveal-delay", `${delay}ms`);
  });

  const revealVisibleItems = () => {
    revealItems.forEach((item) => {
      if (item.classList.contains("is-visible")) return;
      const bounds = item.getBoundingClientRect();
      if (bounds.top < window.innerHeight * 0.94 && bounds.bottom > 0) {
        item.classList.add("is-visible");
      }
    });
  };

  if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    }, {
      rootMargin: "0px 0px -8% 0px",
      threshold: 0.08
    });
    revealItems.forEach((item) => revealObserver.observe(item));
  } else {
    revealItems.forEach((item) => item.classList.add("is-visible"));
  }
  revealVisibleItems();

  const header = document.querySelector(".site-header");
  const updateScrollState = () => {
    const scrollable = document.documentElement.scrollHeight - window.innerHeight;
    const progress = scrollable > 0 ? Math.min(100, (window.scrollY / scrollable) * 100) : 0;
    document.documentElement.style.setProperty("--scroll-progress", `${progress}%`);
    if (header) header.classList.toggle("is-scrolled", window.scrollY > 12);
  };
  updateScrollState();
  window.addEventListener("scroll", () => {
    updateScrollState();
    revealVisibleItems();
  }, { passive: true });
});
