function initializeDetailedGuideTranslations() {
  const roots = DETAILED_GUIDE_ROOT_IDS
    .map((id) => document.getElementById(id))
    .filter(Boolean);
  let textIndex = 0;

  roots.forEach((root) => {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);

    textNodes.forEach((textNode) => {
      const source = textNode.nodeValue.trim();
      if (!source || !/[\u3400-\u9fff]/u.test(source)) return;

      const key = `guide_detail_${String(textIndex).padStart(3, "0")}`;
      const leading = textNode.nodeValue.match(/^\s*/u)?.[0] || "";
      const trailing = textNode.nodeValue.match(/\s*$/u)?.[0] || "";
      const span = document.createElement("span");
      span.dataset.i18n = key;
      span.textContent = source;
      textNode.replaceWith(document.createTextNode(leading), span, document.createTextNode(trailing));

      PH_TRANSLATIONS["zh-Hans"][key] = source;
      textIndex += 1;
    });
  });

  Object.entries(DETAILED_GUIDE_TRANSLATIONS).forEach(([language, values]) => {
    if (values.length !== textIndex) {
      console.error(`Detailed guide translation count mismatch for ${language}: expected ${textIndex}, received ${values.length}`);
    }
    values.forEach((value, index) => {
      PH_TRANSLATIONS[language][`guide_detail_${String(index).padStart(3, "0")}`] = value;
    });
  });
}

