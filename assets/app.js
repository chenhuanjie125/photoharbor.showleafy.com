function normalizeLanguage(language) {
  if (!language) return null;
  const value = String(language).trim();
  const lower = value.toLowerCase();
  if (lower === "zh") return "zh-Hans";
  if (lower === "en") return "en";
  if (lower === "ja") return "ja";
  if (lower === "de") return "de";
  if (lower === "zh-hant" || lower === "zh-tw" || lower === "zh-hk" || lower === "zh-mo") return "zh-Hant";
  if (lower === "zh-hans" || lower.startsWith("zh-cn") || lower.startsWith("zh-sg")) return "zh-Hans";
  if (lower.startsWith("en-")) return "en";
  if (lower.startsWith("ja-")) return "ja";
  if (lower.startsWith("de-")) return "de";
  if (lower.startsWith("zh-")) return "zh-Hans";
  return PH_TRANSLATIONS[value] ? value : null;
}

function detectBrowserLanguage() {
  const candidates = [
    ...(navigator.languages || []),
    navigator.language,
    navigator.userLanguage
  ].filter(Boolean);

  for (const candidate of candidates) {
    const normalized = normalizeLanguage(candidate);
    if (normalized) return normalized;
  }
  return "zh-Hans";
}

function queryLanguagePreference() {
  try {
    const params = new URLSearchParams(window.location.search);
    return normalizeLanguage(params.get("lang"));
  } catch (_) {
    return null;
  }
}

function getTranslation(lang, key) {
  const locale = PH_TRANSLATIONS[lang] || PH_TRANSLATIONS.en;
  return locale[key] ?? PH_TRANSLATIONS.en[key] ?? PH_TRANSLATIONS["zh-Hans"][key] ?? "";
}

function updateLanguageSelectWidth(select) {
  const selectedText = select.selectedOptions[0]?.textContent?.trim() || select.value;
  const measurer = updateLanguageSelectWidth.measurer || document.createElement("span");
  const styles = window.getComputedStyle(select);

  if (!updateLanguageSelectWidth.measurer) {
    measurer.setAttribute("aria-hidden", "true");
    Object.assign(measurer.style, {
      position: "absolute",
      visibility: "hidden",
      whiteSpace: "nowrap",
      pointerEvents: "none",
    });
    document.body.appendChild(measurer);
    updateLanguageSelectWidth.measurer = measurer;
  }

  measurer.style.font = styles.font;
  measurer.textContent = selectedText;
  select.style.setProperty("--lang-select-width", `${Math.ceil(measurer.getBoundingClientRect().width) + 4}px`);
}

function closeLanguageMenu(switcher) {
  const button = switcher.querySelector(".lang-button");
  switcher.classList.remove("is-open");
  if (button) button.setAttribute("aria-expanded", "false");
}

function syncLanguageControl(select) {
  updateLanguageSelectWidth(select);

  const switcher = select.closest(".lang-switch");
  if (!switcher) return;

  const selectedText = select.selectedOptions[0]?.textContent?.trim() || select.value;
  const button = switcher.querySelector(".lang-button");
  if (button) {
    button.textContent = selectedText;
    button.setAttribute("aria-label", select.getAttribute("aria-label") || "Website language");
  }

  switcher.querySelectorAll("[data-lang-option]").forEach((optionButton) => {
    optionButton.setAttribute("aria-selected", optionButton.dataset.langValue === select.value ? "true" : "false");
  });
}

function enhanceLanguageSelect(select) {
  const switcher = select.closest(".lang-switch");
  if (!switcher || switcher.classList.contains("is-enhanced")) return;

  const button = document.createElement("button");
  button.type = "button";
  button.className = "lang-button";
  button.setAttribute("aria-haspopup", "listbox");
  button.setAttribute("aria-expanded", "false");
  button.setAttribute("aria-label", select.getAttribute("aria-label") || "Website language");

  const menu = document.createElement("div");
  menu.className = "lang-menu";
  menu.setAttribute("role", "listbox");

  Array.from(select.options).forEach((option) => {
    const optionButton = document.createElement("button");
    optionButton.type = "button";
    optionButton.setAttribute("role", "option");
    optionButton.dataset.langOption = "";
    optionButton.dataset.langValue = option.value;
    if (option.dataset.i18n) optionButton.dataset.i18n = option.dataset.i18n;
    optionButton.textContent = option.textContent;
    optionButton.addEventListener("click", () => {
      applyLanguage(option.value);
      closeLanguageMenu(switcher);
      button.focus();
    });
    optionButton.addEventListener("keydown", (event) => {
      if (event.key === "Escape") {
        event.preventDefault();
        closeLanguageMenu(switcher);
        button.focus();
      }
    });
    menu.appendChild(optionButton);
  });

  button.addEventListener("click", () => {
    const willOpen = !switcher.classList.contains("is-open");
    document.querySelectorAll(".lang-switch.is-open").forEach(closeLanguageMenu);
    switcher.classList.toggle("is-open", willOpen);
    button.setAttribute("aria-expanded", willOpen ? "true" : "false");
  });

  button.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeLanguageMenu(switcher);
      return;
    }
    if (event.key === "ArrowDown" || event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      switcher.classList.add("is-open");
      button.setAttribute("aria-expanded", "true");
      switcher.querySelector('[data-lang-option][aria-selected="true"]')?.focus();
    }
  });

  switcher.insertBefore(button, select);
  switcher.appendChild(menu);
  switcher.classList.add("is-enhanced");
  syncLanguageControl(select);
}

let guideNavigationObserver = null;

function localeAttributeIncludes(value, language) {
  return String(value || "")
    .split(/[\s,]+/)
    .filter(Boolean)
    .includes(language);
}

function applyLocaleVisibility(language) {
  document.querySelectorAll("[data-locale-only]").forEach((node) => {
    node.hidden = !localeAttributeIncludes(node.dataset.localeOnly, language);
  });
  document.querySelectorAll("[data-locale-except]").forEach((node) => {
    node.hidden = localeAttributeIncludes(node.dataset.localeExcept, language);
  });
}

function setActiveGuideNavigation(sectionID) {
  document.querySelectorAll("[data-guide-nav-group] .toc-subnav a[href^='#']").forEach((link) => {
    const isCurrent = link.getAttribute("href") === `#${sectionID}`;
    link.classList.toggle("is-current", isCurrent);
    if (isCurrent) {
      link.setAttribute("aria-current", "location");
    } else {
      link.removeAttribute("aria-current");
    }
  });
}

function refreshGuideNavigation() {
  if (guideNavigationObserver) {
    guideNavigationObserver.disconnect();
    guideNavigationObserver = null;
  }

  const groups = Array.from(document.querySelectorAll("[data-guide-nav-group]"))
    .filter((menu) => !menu.hidden);
  const enabledGroupNames = new Set(groups.map((menu) => menu.dataset.guideNavGroup));
  const sections = Array.from(document.querySelectorAll("[data-guide-section-group][id]"))
    .filter((section) => enabledGroupNames.has(section.dataset.guideSectionGroup));
  if (!groups.length || !sections.length) {
    setActiveGuideNavigation("");
    return;
  }

  const hashToken = window.location.hash.replace(/^#/, "");
  const hashGroup = groups.find((menu) => menu.dataset.guideNavGroup === hashToken);
  const hashSection = sections.find((section) => section.id === hashToken)
    || (hashGroup
      ? sections.find((section) => section.dataset.guideSectionGroup === hashGroup.dataset.guideNavGroup)
      : null);
  setActiveGuideNavigation((hashSection || sections[0]).id);
  if (hashSection) {
    groups.find((menu) => menu.dataset.guideNavGroup === hashSection.dataset.guideSectionGroup)?.setAttribute("open", "");
  }

  if (!("IntersectionObserver" in window)) return;

  guideNavigationObserver = new IntersectionObserver(() => {
    const activationLine = Math.max(112, window.innerHeight * 0.28);
    const active = sections
      .map((section) => ({ section, bounds: section.getBoundingClientRect() }))
      .filter(({ bounds }) => bounds.bottom > 72)
      .sort((left, right) => Math.abs(left.bounds.top - activationLine) - Math.abs(right.bounds.top - activationLine))[0];
    if (active) setActiveGuideNavigation(active.section.id);
  }, {
    rootMargin: "-18% 0px -62% 0px",
    threshold: [0, 0.05, 0.2]
  });
  sections.forEach((section) => guideNavigationObserver.observe(section));
}

function syncGuideMenusForViewport() {
  const compact = window.matchMedia("(max-width: 980px)").matches;
  document.querySelectorAll("[data-guide-nav-group]").forEach((menu) => {
    if (menu.hidden) return;
    if (!compact) {
      menu.open = true;
      delete menu.dataset.compactInitialized;
      return;
    }

    const containsHash = menu.dataset.guideNavGroup === window.location.hash.replace(/^#/, "")
      || Boolean(menu.querySelector(`a[href="${window.location.hash}"]`));
    if (!menu.dataset.compactInitialized) {
      menu.open = containsHash;
      menu.dataset.compactInitialized = "true";
    } else if (containsHash) {
      menu.open = true;
    }
  });
}

